CREATE TABLE IF NOT EXISTS im_friend (
    user_id         VARCHAR(32) NOT NULL,
    friend_id       VARCHAR(32) NOT NULL,
    status          VARCHAR(16) NOT NULL DEFAULT 'pending',
    remark          VARCHAR(64),
    created_at      TIMESTAMP NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMP NOT NULL DEFAULT NOW(),
    PRIMARY KEY (user_id, friend_id)
);

CREATE INDEX IF NOT EXISTS idx_im_friend_friend ON im_friend (friend_id, status);

CREATE TABLE IF NOT EXISTS im_group (
    id              VARCHAR(32) PRIMARY KEY,
    name            VARCHAR(128) NOT NULL,
    avatar          VARCHAR(512),
    owner_id        VARCHAR(32) NOT NULL,
    notice          VARCHAR(512),
    max_members     INT NOT NULL DEFAULT 500,
    created_at      TIMESTAMP NOT NULL DEFAULT NOW(),
    dissolved_at    TIMESTAMP
);

CREATE TABLE IF NOT EXISTS im_group_member (
    group_id        VARCHAR(32) NOT NULL,
    user_id         VARCHAR(32) NOT NULL,
    role            VARCHAR(16) NOT NULL DEFAULT 'member',
    group_nickname  VARCHAR(64),
    joined_at       TIMESTAMP NOT NULL DEFAULT NOW(),
    muted_until     TIMESTAMP,
    PRIMARY KEY (group_id, user_id)
);

CREATE INDEX IF NOT EXISTS idx_im_group_member_user ON im_group_member (user_id);

CREATE TABLE IF NOT EXISTS im_conversation (
    id              VARCHAR(32) PRIMARY KEY,
    conv_type       VARCHAR(16) NOT NULL,
    group_id        VARCHAR(32),
    user_a_id       VARCHAR(32),
    user_b_id       VARCHAR(32),
    created_at      TIMESTAMP NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_im_conversation_single
    ON im_conversation (user_a_id, user_b_id)
    WHERE conv_type = 'single';

CREATE UNIQUE INDEX IF NOT EXISTS uk_im_conversation_group
    ON im_conversation (group_id)
    WHERE conv_type = 'group';

CREATE TABLE IF NOT EXISTS im_user_inbox (
    user_id                 VARCHAR(32) NOT NULL,
    conversation_id         VARCHAR(32) NOT NULL,
    unread_count            INT NOT NULL DEFAULT 0,
    last_read_message_id    BIGINT NOT NULL DEFAULT 0,
    last_message_id         BIGINT,
    last_content            VARCHAR(256),
    last_time               TIMESTAMP,
    pinned                  BOOLEAN NOT NULL DEFAULT FALSE,
    muted                   BOOLEAN NOT NULL DEFAULT FALSE,
    updated_at              TIMESTAMP NOT NULL DEFAULT NOW(),
    PRIMARY KEY (user_id, conversation_id)
);

CREATE INDEX IF NOT EXISTS idx_im_user_inbox_user_time ON im_user_inbox (user_id, last_time DESC);

CREATE TABLE IF NOT EXISTS im_message (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_msg_id       VARCHAR(64) NOT NULL,
    conversation_id     VARCHAR(32) NOT NULL,
    sender_id           VARCHAR(32) NOT NULL,
    content             TEXT NOT NULL,
    msg_type            VARCHAR(16) NOT NULL DEFAULT 'TEXT',
    created_at          TIMESTAMP NOT NULL DEFAULT NOW(),
    UNIQUE (conversation_id, sender_id, client_msg_id)
);

CREATE INDEX IF NOT EXISTS idx_im_message_conv_id ON im_message (conversation_id, id);

ALTER TABLE im_message ALTER COLUMN content TYPE TEXT;

ALTER TABLE im_message ADD COLUMN IF NOT EXISTS recalled_at TIMESTAMP;
ALTER TABLE im_message ADD COLUMN IF NOT EXISTS quote_message_id BIGINT;

CREATE TABLE IF NOT EXISTS im_message_hidden (
    user_id         VARCHAR(32) NOT NULL,
    message_id      BIGINT NOT NULL,
    conversation_id VARCHAR(32) NOT NULL,
    hidden_at       TIMESTAMP NOT NULL DEFAULT NOW(),
    PRIMARY KEY (user_id, message_id)
);

CREATE INDEX IF NOT EXISTS idx_im_message_hidden_conv
    ON im_message_hidden (user_id, conversation_id);

CREATE TABLE IF NOT EXISTS im_user_crypto (
    user_id         VARCHAR(32) PRIMARY KEY,
    public_key_spki TEXT NOT NULL,
    key_proof       TEXT NOT NULL,
    created_at      TIMESTAMP NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMP NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS im_group_key_wrap (
    group_id        VARCHAR(32) NOT NULL,
    user_id         VARCHAR(32) NOT NULL,
    key_version     INT NOT NULL DEFAULT 1,
    wrapped_key     TEXT NOT NULL,
    updated_at      TIMESTAMP NOT NULL DEFAULT NOW(),
    PRIMARY KEY (group_id, user_id)
);

CREATE INDEX IF NOT EXISTS idx_im_group_key_wrap_group
    ON im_group_key_wrap (group_id, key_version);
